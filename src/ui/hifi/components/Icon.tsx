export type IconName = keyof typeof P;

export function Icon({
  name,
  size = 15,
  className,
  strokeWidth = 1.8,
  style,
}: {
  name: IconName | string;
  size?: number;
  className?: string;
  strokeWidth?: number;
  style?: React.CSSProperties;
}) {
  const content = P[name as string];
  if (!content) {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" className={className} style={style} aria-hidden="true" data-icon={String(name)}>
        <circle cx="12" cy="12" r="9" />
      </svg>
    );
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      aria-hidden="true"
      focusable="false"
      /* 图标名进 DOM：视觉上无影响，但让"这一格到底是哪个图标"可被断言 ——
         侧栏的任务状态位靠图标形状区分（手/八角/眼睛/放射条），
         只比 class 或尺寸判不出是哪一个。 */
      data-icon={name as string}
    >
      {content}
    </svg>
  );
}
